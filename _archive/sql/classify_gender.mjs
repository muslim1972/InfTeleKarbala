function normalizeArabic(text) {
  return text
    .trim()
    .replace(/[ًٌٍَُِّْ]/g, '') // remove diacritics
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, ' ');
}

