const AMBIGUOUS_NAMES = new Set([
  'صفاء', 'صباح', 'وسام', 'نور', 'نضال', 'نجاح', 'رجاء', 'فداء', 'تيسير', 'نهاد',
  'عصمت', 'طلعت', 'رفعت', 'مدحت', 'حكمت', 'عطيه', 'نبراس', 'ميثاق',
  'اسلام', 'احسان', 'وفاء', 'ضياء', 'اكرام', 'براء', 'جهاد', 'ولاء', 'علياء'
].map(normalizeArabic));

function getFirstWord(normFullName) {
  const parts = normFullName.split(' ');
  if (parts.length === 0) return '';
  const p0 = parts[0];
  const p1 = parts[1] || '';
  
  if (['عبد', 'ابو', 'ابن', 'ام'].includes(p0)) {
    return `${p0} ${p1}`;
  }
  if (p0.startsWith('عبد') && p0.length > 3) {
    return p0;
  }
  if (p0 === 'محمد' && ['علي', 'حسن', 'حسين', 'باقر', 'صادق', 'جواد', 'رضا', 'مهدي', 'امين'].includes(p1)) {
    return `${p0} ${p1}`;
  }
  if (p0 === 'نور' && p1 === 'الهدي') {
    return 'نور الهدي';
  }
  return p0;
}

function classify(fullName) {
  const norm = normalizeArabic(fullName);
  if (norm.startsWith('تجريبي') || norm.includes('test') || norm.length < 2) {
    return { gender: 'unspecified', reason: 'تجريبي / غير مكتمل' };
  }

  const first = getFirstWord(norm);
  const rawFirst = norm.split(' ')[0];

  // Compound male with عبد / ابو / ابن
  if (first.startsWith('عبد ') || first.startsWith('عبد') || first.startsWith('ابو ') || first.startsWith('ابن ')) {
    return { gender: 'male', reason: 'مركب مذكر (عبد/أبو)' };
  }

  // Compound female with ام / نور الهدى
  if (first.startsWith('ام ') || first === 'نور الهدي') {
    return { gender: 'female', reason: 'مركب مؤنث (أم/نور الهدى)' };
  }

  // Ambiguous check
  if (AMBIGUOUS_NAMES.has(rawFirst) || AMBIGUOUS_NAMES.has(first)) {
    return { gender: 'unspecified', reason: `اسم مشترك/ملتبس (${rawFirst})` };
  }

  // Female Dictionary
  if (FEMALE_NAMES.has(rawFirst) || FEMALE_NAMES.has(first)) {
    return { gender: 'female', reason: 'قاموس الإناث' };
  }

  // Male Dictionary
  if (MALE_NAMES.has(rawFirst) || MALE_NAMES.has(first)) {
    return { gender: 'male', reason: 'قاموس الذكور' };
  }

  // Feminine Ending Heuristic (هـ / ة / ت التأنيثية)
  const maleWithTeh = new Set(['حمزه', 'اسامه', 'طلحه', 'قتيبه', 'حذيفه', 'عبيده', 'عكرمه', 'معاويه', 'سلامه', 'جمعه', 'عطيه', 'نعمه', 'عروه', 'خليفه', 'شيبه'].map(normalizeArabic));
  if ((rawFirst.endsWith('ه') || rawFirst.endsWith('ة')) && !maleWithTeh.has(rawFirst)) {
    return { gender: 'female', reason: 'علامة تأنيث واضحة' };
  }

  return { gender: 'unspecified', reason: `غير متيقن (${rawFirst})` };
}

let stats = {
  total: 0,
  male: 0,
  female: 0,
  unspecified: 0,
  byGov: {}
};

const updates = [];

for (const line of lines) {
  const parts = line.split('|');
  if (parts.length < 2) continue;
  const id = parts[0].trim();
  const fullName = parts[1].trim();
  const gov = (parts[2] || 'unknown').trim();

  stats.total++;
  if (!stats.byGov[gov]) stats.byGov[gov] = { male: 0, female: 0, unspecified: 0, total: 0 };
  stats.byGov[gov].total++;

  const res = classify(fullName);
  stats[res.gender]++;
  stats.byGov[gov][res.gender]++;

  // If unspecified, set to NULL so profiles_gender_check passes and COALESCE(gender, 'unspecified') works perfectly!
  const sqlVal = res.gender === 'unspecified' ? 'NULL' : `'${res.gender}'`;
  updates.push(`UPDATE profiles SET gender = ${sqlVal} WHERE id = '${id}';`);
}

// Write SQL
const sqlContent = `-- Auto-generated gender classification for 941 profiles
BEGIN;
${updates.join('\n')}
COMMIT;
`;

fs.writeFileSync('D:/InfTeleKarbala/_archive/sql/update_gender.sql', sqlContent, 'utf-8');
